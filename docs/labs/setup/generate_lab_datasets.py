#!/usr/bin/env python3
"""Generate the prepared datasets used by NS-401 labs (Lab-02..Lab-15).

All traffic is SYNTHETIC and benign-shaped: it is evidence for defensive
analysis, built from empty payloads and normal-sized fields. No exploit code,
no destructive or persistence mechanisms — the "attack" datasets contain only
the observable telemetry signatures (unsolicited ARP replies, uncompleted SYN
waves, periodic beacon-shaped queries) that the labs teach students to detect.

Pure standard library. Deterministic output (seeded). Run:

    python docs/labs/setup/generate_lab_datasets.py

Outputs to docs/labs/datasets/ and rewrites SHA256SUMS there.
Datasets produced:
  lab02-normal-traffic.pcap   handshakes, HTTP-shaped, DNS, DHCP DORA
  lab03-l2-attacks.pcap       ARP scan + unsolicited ARP replies + DHCP starvation burst
  lab04-mitm-flood.pcap       TCP SYN wave (uncompleted) + UDP amplify-shaped pairs
  lab11-flows.csv             flow records (NetFlow-v5-style columns) incl. beacon+scan
  lab13-incident.pcap         staged intrusion: scan, C2 beacon (DNS TXT), exfil-shaped POST
  lab15-forensics.pcap        same corpus family, wider window, for timeline work
Every dataset is regenerated byte-identically from the seed — reproducibility
is itself an evidence-discipline lesson (see Lab-15 chain-of-custody task).
"""
from __future__ import annotations
import csv
import hashlib
import random
import struct
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "datasets"
OUT.mkdir(parents=True, exist_ok=True)

MAC_A = bytes.fromhex("02005555AAAA")   # attacker / anomalous host
MAC_R1 = bytes.fromhex("02005555AAA1")  # regular host 1
MAC_R2 = bytes.fromhex("02005555AAA2")  # regular host 2
MAC_R3 = bytes.fromhex("02005555AAA3")  # regular host 3
MAC_GW = bytes.fromhex("02005555GG01".replace("GG", "11"))  # gateway 02:00:55:55:11:01
MAC_SRV = bytes.fromhex("02005555BB01")  # internal server

IP_A = "10.20.0.66"       # attacker
IP_R1 = "10.20.0.101"
IP_R2 = "10.20.0.102"
IP_R3 = "10.20.0.103"
IP_GW = "10.20.0.1"
IP_SRV = "10.20.30.10"
IP_DNS = "10.20.30.53"
IP_EXT = "203.0.113.7"    # TEST-NET-3 external "C2"
IP_EXT2 = "198.51.100.9"  # TEST-NET-2


def ip2b(s: str) -> bytes:
    return bytes(int(x) for x in s.split("."))


def cksum(data: bytes) -> int:
    if len(data) % 2:
        data += b"\x00"
    s = sum(struct.unpack("!%dH" % (len(data) // 2), data))
    s = (s >> 16) + (s & 0xFFFF)
    s += s >> 16
    return (~s) & 0xFFFF


def eth(dst: bytes, src: bytes, etype: int, payload: bytes) -> bytes:
    return dst + src + struct.pack("!H", etype) + payload


def ipv4(src: str, dst: str, proto: int, payload: bytes, ident: int, ttl: int = 64) -> bytes:
    total = 20 + len(payload)
    hdr = struct.pack("!BBHHHBBH4s4s", 0x45, 0, total, ident & 0xFFFF, 0x4000,
                      ttl, proto, 0, ip2b(src), ip2b(dst))
    hdr = hdr[:10] + struct.pack("!H", cksum(hdr)) + hdr[12:]
    return hdr + payload


def udp(sp: int, dp: int, payload: bytes, src: str, dst: str) -> bytes:
    length = 8 + len(payload)
    pseudo = ip2b(src) + ip2b(dst) + struct.pack("!BBH", 0, 17, length)
    csum = cksum(pseudo + struct.pack("!HHHH", sp, dp, length, 0) + payload) or 0xFFFF
    return struct.pack("!HHHH", sp, dp, length, csum) + payload


def tcp(sp: int, dp: int, seq: int, ack: int, flags: int, payload: bytes,
        src: str, dst: str, window: int = 8192) -> bytes:
    offset = 5 << 12
    pseudo = ip2b(src) + ip2b(dst) + struct.pack("!BBH", 0, 6, 20 + len(payload))
    seg = struct.pack("!HHIIBBHHH", sp, dp, seq, ack, (5 << 4), flags, window, 0, 0) + payload
    csum = cksum(pseudo + seg) or 0xFFFF
    seg = seg[:16] + struct.pack("!H", csum) + seg[18:]
    return seg


FIN, SYN, RST, PSH, ACK = 0x01, 0x02, 0x04, 0x08, 0x10


def qname(name: str) -> bytes:
    out = b""
    for label in name.split("."):
        out += bytes([len(label)]) + label.encode()
    return out + b"\x00"


def dns_query(txid: int, name: str, qtype: int = 1) -> bytes:
    return (struct.pack("!HHHHHH", txid, 0x0100, 1, 0, 0, 0) + qname(name)
            + struct.pack("!HH", qtype, 1))


def dns_response(txid: int, name: str, addr: str, qtype: int = 1) -> bytes:
    ans = (b"\xc0\x0c" + struct.pack("!HHIH", qtype, 1, 300, 4) + ip2b(addr))
    return (struct.pack("!HHHHHH", txid, 0x8180, 1, 1, 0, 0) + qname(name)
            + struct.pack("!HH", qtype, 1) + ans)


def dhcp(op: int, xid: int, chaddr: bytes, opt53: int,
         yiaddr: str = "0.0.0.0", siaddr: str = "0.0.0.0", opts: bytes = b"") -> bytes:
    pkt = struct.pack("!BBBBIHH", op, 1, 6, 0, xid, 0, op == 1 and 0x0000 or 0x8000)
    pkt += ip2b("0.0.0.0") + ip2b(yiaddr) + ip2b(siaddr) + ip2b("0.0.0.0")
    pkt += chaddr + b"\x00" * 10
    pkt += b"\x00" * 64 + b"\x00" * 128
    pkt += struct.pack("!I", 0x63825363)
    pkt += bytes([53, 1, opt53])
    if siaddr != "0.0.0.0" and opt53 == 5:
        pkt += bytes([54, 4]) + ip2b(siaddr)
        pkt += bytes([51, 4]) + struct.pack("!I", 3600)
    pkt += opts + b"\xff"
    return pkt


class Pcap:
    def __init__(self) -> None:
        self.buf = struct.pack("!IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, 1)
        self.t = 1_700_000_000.0
        self.n = 0

    def add(self, frame: bytes, dt: float) -> None:
        ts = self.t
        self.t += dt
        self.n += 1
        self.buf += struct.pack("!IIII", int(ts), int(round(ts % 1 * 1_000_000)),
                                len(frame), len(frame)) + frame

    def write(self, name: str) -> Path:
        p = OUT / name
        p.write_bytes(self.buf)
        return p


def ip_id(rng: random.Random) -> int:
    return rng.randint(1, 0xFFFE)


def handshake(p: Pcap, rng: random.Random, cmac: bytes, cip: str, sip: str,
              sport: int, dport: int, dt: float = 0.001) -> None:
    seq_c, seq_s = rng.randint(10**5, 10**8), rng.randint(10**5, 10**8)
    p.add(eth(MAC_GW, cmac, 0x0800, ipv4(cip, sip, 6, tcp(sport, dport, seq_c, 0, SYN, b"", cip, sip), ip_id(rng))), dt)
    p.add(eth(cmac, MAC_GW, 0x0800, ipv4(sip, cip, 6, tcp(dport, sport, seq_s, seq_c + 1, SYN | ACK, b"", sip, cip), ip_id(rng))), dt)
    p.add(eth(MAC_GW, cmac, 0x0800, ipv4(cip, sip, 6, tcp(sport, dport, seq_c + 1, seq_s + 1, ACK, b"", cip, sip), ip_id(rng))), dt)
    return seq_c, seq_s


def http_get(p: Pcap, rng: random.Random, cmac: bytes, cip: str, host: str, path: str) -> None:
    sport = rng.randint(40000, 60000)
    seq_c, seq_s = handshake(p, rng, cmac, cip, IP_SRV, sport, 80)
    req = f"GET {path} HTTP/1.1\r\nHost: {host}\r\nUser-Agent: lab-client/1.0\r\n\r\n".encode()
    resp = b"HTTP/1.1 200 OK\r\nContent-Type: text/html\r\nContent-Length: 21\r\n\r\n<html>lab page</html>"
    p.add(eth(MAC_GW, cmac, 0x0800, ipv4(cip, IP_SRV, 6, tcp(sport, 80, seq_c + 1, seq_s + 1, PSH | ACK, req, cip, IP_SRV), ip_id(rng))), 0.002)
    seq_s2 = seq_s + 1
    p.add(eth(cmac, MAC_GW, 0x0800, ipv4(IP_SRV, cip, 6, tcp(80, sport, seq_s2, seq_c + 1 + len(req), PSH | ACK, resp, IP_SRV, cip), ip_id(rng))), 0.02)
    p.add(eth(MAC_GW, cmac, 0x0800, ipv4(cip, IP_SRV, 6, tcp(sport, 80, seq_c + 1 + len(req), seq_s2 + len(resp), ACK, b"", cip, IP_SRV), ip_id(rng))), 0.001)
    p.add(eth(MAC_GW, cmac, 0x0800, ipv4(cip, IP_SRV, 6, tcp(sport, 80, seq_c + 1 + len(req), seq_s2 + len(resp), FIN | ACK, b"", cip, IP_SRV), ip_id(rng))), 0.3)
    p.add(eth(cmac, MAC_GW, 0x0800, ipv4(IP_SRV, cip, 6, tcp(80, sport, seq_s2 + len(resp), seq_c + 2 + len(req), FIN | ACK, b"", IP_SRV, cip), ip_id(rng))), 0.001)


def dns_exchange(p: Pcap, rng: random.Random, cmac: bytes, cip: str, name: str,
                 qtype: int = 1, answer: str | None = "10.20.30.53") -> None:
    sport = rng.randint(40000, 60000)
    txid = rng.randint(1, 0xFFFE)
    q = dns_query(txid, name, qtype)
    p.add(eth(MAC_GW, cmac, 0x0800, ipv4(cip, IP_DNS, 17, udp(sport, 53, q, cip, IP_DNS), ip_id(rng))), 0.001)
    if answer is not None:
        r = dns_response(txid, name, answer, qtype)
        p.add(eth(cmac, MAC_GW, 0x0800, ipv4(IP_DNS, cip, 17, udp(53, sport, r, IP_DNS, cip), ip_id(rng))), 0.004)


def dora(p: Pcap, rng: random.Random, cmac: bytes, cip: str, xid: int) -> None:
    disc = dhcp(1, xid, cmac, 1)
    p.add(eth(b"\xff" * 6, cmac, 0x0800, ipv4("0.0.0.0", "255.255.255.255", 17,
          udp(68, 67, disc, "0.0.0.0", "255.255.255.255"), ip_id(rng))), 0.001)
    off = dhcp(2, xid, cmac, 2, yiaddr=cip, siaddr=IP_GW)
    p.add(eth(cmac, MAC_GW, 0x0800, ipv4(IP_GW, "255.255.255.255", 17,
          udp(67, 68, off, IP_GW, "255.255.255.255"), ip_id(rng))), 0.002)
    req = dhcp(1, xid, cmac, 3, opts=bytes([50, 4]) + ip2b(cip))
    p.add(eth(b"\xff" * 6, cmac, 0x0800, ipv4("0.0.0.0", "255.255.255.255", 17,
          udp(68, 67, req, "0.0.0.0", "255.255.255.255"), ip_id(rng))), 0.001)
    ack = dhcp(2, xid, cmac, 5, yiaddr=cip, siaddr=IP_GW)
    p.add(eth(cmac, MAC_GW, 0x0800, ipv4(IP_GW, "255.255.255.255", 17,
          udp(67, 68, ack, IP_GW, "255.255.255.255"), ip_id(rng))), 0.002)


def arp(oper: int, sha: bytes, spa: str, tha: bytes, tpa: str) -> bytes:
    return struct.pack("!HHBBH", 1, 0x0800, 6, 4, oper) + sha + ip2b(spa) + tha + ip2b(tpa)


# ---------------------------------------------------------------- scenarios
def lab02_normal() -> Path:
    rng = random.Random(402)
    p = Pcap()
    dora(p, rng, MAC_R1, IP_R1, 0x11220001)
    dora(p, rng, MAC_R2, IP_R2, 0x11220002)
    for i, host in enumerate([(MAC_R1, IP_R1), (MAC_R2, IP_R2), (MAC_R3, IP_R3)]):
        cmac, cip = host
        for name in [f"www{i}.lab.example", "updates.lab.example", "portal.lab.example"]:
            dns_exchange(p, rng, cmac, cip, name)
        http_get(p, rng, cmac, cip, "portal.lab.example", "/index.html")
    # a clean TCP session with teardown to remote NTP-like service
    sport = rng.randint(40000, 60000)
    seq_c, seq_s = handshake(p, rng, MAC_R3, IP_R3, IP_EXT2, sport, 123, dt=0.5)
    p.add(eth(MAC_GW, MAC_R3, 0x0800, ipv4(IP_R3, IP_EXT2, 6, tcp(sport, 123, seq_c + 1, seq_s + 1, FIN | ACK, b"", IP_R3, IP_EXT2), ip_id(rng))), 5.0)
    return p.write("lab02-normal-traffic.pcap")


def lab03_l2_attacks() -> Path:
    rng = random.Random(403)
    p = Pcap()
    # normal background first
    dora(p, rng, MAC_R1, IP_R1, 0x33000001)
    dns_exchange(p, rng, MAC_R1, IP_R1, "portal.lab.example")
    # ARP sweep: attacker probes a /24 (who-has, unreplied)
    for host in range(100, 112):
        tpa = f"10.20.0.{host}"
        p.add(eth(b"\xff" * 6, MAC_A, 0x0806, arp(1, MAC_A, IP_A, b"\x00" * 6, tpa)), 0.02)
    # ARP spoofing: unsolicited gratuitous-style replies claiming the gateway IP
    for _ in range(6):
        p.add(eth(MAC_R1, MAC_A, 0x0806, arp(2, MAC_A, IP_GW, MAC_R1, IP_GW)), 0.5)
        p.add(eth(MAC_R2, MAC_A, 0x0806, arp(2, MAC_A, IP_GW, MAC_R2, IP_GW)), 0.5)
    # a victim's frame then transits toward the attacker MAC (visibility consequence)
    http_get(p, rng, MAC_R1, IP_R1, "portal.lab.example", "/login.html")
    # DHCP starvation: 8 Discover bursts from spoofed client MACs, then rogue server offers
    for i in range(8):
        fake = bytes.fromhex("02005555DD%02X" % i)
        disc = dhcp(1, 0x44000000 + i, fake, 1)
        p.add(eth(b"\xff" * 6, fake, 0x0800, ipv4("0.0.0.0", "255.255.255.255", 17,
              udp(68, 67, disc, "0.0.0.0", "255.255.255.255"), ip_id(rng))), 0.01)
    for i in range(8):
        fake = bytes.fromhex("02005555DD%02X" % i)
        offer = dhcp(2, 0x44000000 + i, fake, 2, yiaddr="10.20.0.200", siaddr=IP_A)
        p.add(eth(fake, MAC_A, 0x0800, ipv4(IP_A, "255.255.255.255", 17,
              udp(67, 68, offer, IP_A, "255.255.255.255"), ip_id(rng))), 0.01)
    return p.write("lab03-l2-attacks.pcap")


def lab04_mitm_flood() -> Path:
    rng = random.Random(404)
    p = Pcap()
    # background
    dns_exchange(p, rng, MAC_R2, IP_R2, "portal.lab.example")
    # SYN wave: 120 SYNs to server:443, never completed
    for i in range(120):
        fake_ip = f"198.51.100.{(i % 200) + 10}"
        p.add(eth(MAC_GW, MAC_A, 0x0800, ipv4(fake_ip, IP_SRV, 6,
              tcp(1024 + i, 443, rng.randint(10**5, 10**8), 0, SYN, b"", fake_ip, IP_SRV),
              ip_id(rng))), 0.01)
    # UDP amplify-shaped pairs: tiny query from spoofed source, large reply to victim
    for i in range(40):
        q = b"\x00\x01" + b"\x01\x00" + b"\x00\x01\x00\x00\x00\x00\x00\x00" + qname("any.lab.example") + struct.pack("!HH", 255, 1)
        p.add(eth(MAC_GW, MAC_A, 0x0800, ipv4(f"198.51.100.{(i % 200) + 10}", IP_DNS, 17,
              udp(53, 53, q, f"198.51.100.{(i % 200) + 10}", IP_DNS), ip_id(rng))), 0.01)
        big = b"\x00\x01\x84\x00" + b"\x00\x01\x00\x01\x00\x00\x00\x00" + qname("any.lab.example") + struct.pack("!HH", 255, 1) + (b"\x41" * 900)
        p.add(eth(MAC_R1, MAC_GW, 0x0800, ipv4(IP_DNS, IP_R1, 17,
              udp(53, 40000 + i, big, IP_DNS, IP_R1), ip_id(rng))), 0.01)
    return p.write("lab04-mitm-flood.pcap")


def incident_corpus(p: Pcap, rng: random.Random, with_beacon: bool = True,
                    with_exfil: bool = True) -> None:
    # business-hours background
    for host in [(MAC_R1, IP_R1), (MAC_R2, IP_R2), (MAC_R3, IP_R3)]:
        dns_exchange(p, rng, host[0], host[1], "portal.lab.example")
        http_get(p, rng, host[0], host[1], "portal.lab.example", "/dashboard")
    # reconnaissance: TCP SYN sweep of server subnet
    for port in [22, 80, 443, 445, 3389]:
        p.add(eth(MAC_GW, MAC_A, 0x0800, ipv4(IP_A, IP_SRV, 6,
              tcp(20000 + port, port, rng.randint(10**5, 10**8), 0, SYN, b"", IP_A, IP_SRV), ip_id(rng))), 0.4)
    if with_beacon:
        # C2 beacon: regular ~30s DNS TXT queries with high-entropy subdomains to TEST-NET
        for i in range(24):
            label = "".join(rng.choice("abcdefghijklmnopqrstuvwxyz234567") for _ in range(26))
            name = f"{label}.cdn-metrics.example"
            sport = rng.randint(40000, 60000)
            txid = rng.randint(1, 0xFFFE)
            q = dns_query(txid, name, 16)
            p.add(eth(MAC_GW, MAC_R2, 0x0800, ipv4(IP_R2, IP_DNS, 17,
                  udp(sport, 53, q, IP_R2, IP_DNS), ip_id(rng))), 30.0)
    if with_exfil:
        # exfil-shaped: periodic small POSTs to external host over HTTP
        sport = rng.randint(40000, 60000)
        seq_c, seq_s = handshake(p, rng, MAC_R2, IP_R2, IP_EXT, sport, 80, dt=0.2)
        for i in range(6):
            body = b"chunk=" + bytes([rng.randint(97, 122)]) * 64
            req = b"POST /upload HTTP/1.1\r\nHost: " + IP_EXT.encode() + b"\r\nContent-Length: " + str(len(body)).encode() + b"\r\n\r\n" + body
            p.add(eth(MAC_GW, MAC_R2, 0x0800, ipv4(IP_R2, IP_EXT, 6,
                  tcp(sport, 80, seq_c + 1, seq_s + 1, PSH | ACK, req, IP_R2, IP_EXT), ip_id(rng))), 120.0)


def lab13_incident() -> Path:
    p = Pcap()
    incident_corpus(p, random.Random(413))
    return p.write("lab13-incident.pcap")


def lab15_forensics() -> Path:
    p = Pcap()
    incident_corpus(p, random.Random(415))
    return p.write("lab15-forensics.pcap")


def lab11_flows() -> Path:
    rng = random.Random(411)
    rows = []
    t = 1_700_000_000

    def flow(ts, dur, src, dst, sp, dp, proto, pkts, byts, flags: str = "AP"):
        rows.append([int(ts), round(dur, 3), src, dst, sp, dp, proto, pkts, byts, flags])

    # normal background: ~40 flows, mixed sizes
    for i in range(40):
        src = rng.choice([IP_R1, IP_R2, IP_R3])
        dst = rng.choice([IP_SRV, IP_DNS, IP_EXT2])
        dp = rng.choice([53, 80, 443, 123])
        pk = rng.randint(4, 40)
        flow(t + i * 7, rng.uniform(0.05, 3.0), src, dst, rng.randint(40000, 60000), dp, 17 if dp in (53, 123) else 6, pk, pk * rng.randint(80, 1400))
    # beacon flows: periodic ~30s, small, uniform, R2 -> TEST-NET via DNS
    for i in range(24):
        flow(t + 600 + i * 30, 0.02, IP_R2, IP_DNS, 40000 + i, 53, 17, 2, 196, flags=".")
    # scan flows: one source, many ports, tiny, one-way
    for port in [21, 22, 23, 25, 80, 110, 135, 139, 443, 445, 1433, 3306, 3389, 5900, 8080]:
        flow(t + 300 + port % 5, 0.001, IP_A, IP_SRV, 20000 + port, port, 6, 1, 60, flags="S")
    p = OUT / "lab11-flows.csv"
    with p.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["first_switched", "duration_s", "src_ip", "dst_ip", "src_port",
                    "dst_port", "protocol", "packets", "bytes", "tcp_flags"])
        w.writerows(rows)
    return p


def main() -> None:
    files = [lab02_normal(), lab03_l2_attacks(), lab04_mitm_flood(),
             lab13_incident(), lab15_forensics(), lab11_flows()]
    lines = []
    for f in sorted(OUT.iterdir()):
        if f.name == "SHA256SUMS" or f.suffix == ".sums":
            continue
        lines.append(f"{hashlib.sha256(f.read_bytes()).hexdigest()}  {f.name}")
    (OUT / "SHA256SUMS").write_text("\n".join(lines) + "\n")
    print(f"generated {len(files)} datasets in {OUT}")
    for f in files:
        print(f"  {f.name:28s} {f.stat().st_size:>9,d} bytes")


if __name__ == "__main__":
    main()
